-- ===== TABLA PRODUCTOS =====
create table if not exists productos (
  id text primary key,
  nombre text not null,
  descripcion text,
  imagen text,
  precio_compra numeric default 0,
  precio_venta numeric default 0,
  stock integer default 0,
  creado_en timestamptz default now()
);
alter table productos enable row level security;
drop policy if exists "productos lectura publica" on productos;
drop policy if exists "productos escritura auth" on productos;
create policy "productos lectura publica" on productos for select using (true);
create policy "productos escritura auth" on productos for all
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

-- ===== TABLA VENTAS =====
create table if not exists ventas (
  id bigint generated by default as identity primary key,
  codigo text,
  total numeric,
  items jsonb,
  fecha timestamptz default now()
);
alter table ventas enable row level security;
drop policy if exists "ventas auth" on ventas;
create policy "ventas auth" on ventas for all
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

